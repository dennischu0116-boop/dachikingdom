import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import babel from '@babel/core';
const read = name=>fs.readFileSync('.gas-test/'+name,'utf8');
const id = '1aLEZaabh42IV9BTWEz9JXEehVolipj37eq330UwY9iyGLA3wMbNgupeZ';
assert.equal(JSON.parse(read('.clasp.json')).scriptId,id);
for(const name of fs.readdirSync('.gas-test').filter(n=>n.endsWith('.html'))) assert(!/['"]qing_(?!redesign_test_)/.test(read(name)), name+' has production browser storage');
const index=read('Index.html');
assert(index.includes('前端測試版・獨立存檔'));
const jsx=[...index.matchAll(/include\('([^']+)'\)/g)].filter(m=>m[1]!=='Styles').map(m=>read(m[1]+'.html')).join('\n');
babel.transformSync(jsx,{presets:['@babel/preset-react'],configFile:false,babelrc:false});
// No Google persistence APIs are provided: any accidental access fails the test.
const context=vm.createContext({});
const source=read('程式碼.js')+'\n'+read('CodeSave.js');
vm.runInContext(source,context);
assert(!/DriveApp|SpreadsheetApp|PropertiesService|UrlFetchApp/.test(source));
assert.equal(context.getCloudPublicConfig().oauthReady,false);
const before=JSON.stringify(context.getLeaderboard());
const result=context.getLeaderboard();
assert.equal(result.data.length,24);
assert(result.data.some(r=>r.gameWon)&&result.data.some(r=>!r.gameWon));
assert.equal(new Set(result.data.map(r=>r.gameId)).size,24);
for(const field of ['years','maxMinisterScore','maxChildScore','maxTreasury','maxConsortCount','maxDescendantCount']) assert(result.data.every(r=>Number.isFinite(r[field])));
assert.equal(context.submitLeaderboardScore({gameId:'real-player'}).skipped,true);
assert.equal(context.importExistingLeaderboardScores([{gameId:'real-player'}]).skipped,true);
assert.equal(JSON.stringify(context.getLeaderboard()),before);
assert(!read('ClientShell.html').includes('<button onClick={onCloud}'));
assert(!read('AppWarAndMain.html').includes('<button onClick={()=>setShowCloudPanel(true)}'));
assert(read('AppModals.html').includes('固定假資料'));
// Exercise the transformed submit function: it must continue callbacks without RPC.
const app=read('AppState.html');
const start=app.indexOf('const submitScore =');
const end=app.indexOf('// 舊玩家紀錄遷移',start);
const submitContext=vm.createContext({gameState:{},calls:0});
vm.runInContext(app.slice(start,end)+'\nsubmitScore({},true,()=>calls++);',submitContext);
assert.equal(submitContext.calls,1);
assert(app.includes('const initialCloudBinding=null;'));
assert(app.includes('const config={oauthReady:false,maxSlots:0};'));
console.log('Test isolation passed: JSX, local storage separation, no login or persistence APIs, fixed rankings, disabled uploads with callback completion.');
